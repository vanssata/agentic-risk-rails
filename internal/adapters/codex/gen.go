const (
	profileName = "riskrails"
	// maxSubagents follows DES §6 "parallel ≤ 3 on BALANCED".
	maxSubagents = 3
	// hookTimeout (seconds) is above rr guard's own deadline; Codex fails OPEN on timeout.
	hookTimeout = 10
	hookMatcher = "Bash|apply_patch|mcp__.*"
	// hookCommand turns every rr failure (crash, missing binary, odd exit code) into exit 2,
	// because Codex continues the tool call when a hook fails with any other code.
	hookCommand = "rr guard --runtime codex --event PreToolUse || exit 2"
)

// ---- .codex/config.toml ----

type configFile struct {
	DefaultPermissions    string                    `toml:"default_permissions"`
	SandboxMode           string                    `toml:"sandbox_mode"`
	ApprovalPolicy        string                    `toml:"approval_policy"`
	SandboxWorkspaceWrite sandboxWorkspaceWrite     `toml:"sandbox_workspace_write"`
	Agents                agentsSection             `toml:"agents"`
	Permissions           map[string]permissionsDef `toml:"permissions"`
	MCPServers            map[string]mcpServer      `toml:"mcp_servers"`
}

// mcpServer registers `rr mcp`. Its tools (triage, research, status) are
// read-only, so approval is automatic; at L2 "prompt" would have nobody to answer.
type mcpServer struct {
	Command                  string   `toml:"command"`
	Args                     []string `toml:"args"`
	EnabledTools             []string `toml:"enabled_tools"`
	DefaultToolsApprovalMode string   `toml:"default_tools_approval_mode"`
}

type sandboxWorkspaceWrite struct {
	NetworkAccess bool `toml:"network_access"`
}

type agentsSection struct {
	DefaultSubagentModel           string `toml:"default_subagent_model,omitempty"`
	DefaultSubagentReasoningEffort string `toml:"default_subagent_reasoning_effort,omitempty"`
	MaxConcurrentThreads           int    `toml:"max_concurrent_threads_per_session"`
}

type permissionsDef struct {
	Filesystem map[string]any `toml:"filesystem"`
}

type configGen struct{}

func (configGen) Name() string { return "codex-config" }

func (configGen) Render(_ context.Context, in core.SyncInput) ([]core.File, error) {
	cfg := configFile{
		DefaultPermissions: profileName,
		SandboxMode:        "workspace-write",
		ApprovalPolicy:     "on-request",
		Agents:             agentsSection{MaxConcurrentThreads: maxSubagents},
		Permissions:        map[string]permissionsDef{profileName: {Filesystem: filesystem(in)}},
		MCPServers:         map[string]mcpServer{"rr": {Command: "rr", Args: []string{"mcp"}, EnabledTools: []string{"triage", "research", "status"}, DefaultToolsApprovalMode: "approve"}},
	}
	if in.Level >= core.L2 {
		cfg.ApprovalPolicy = "never" // ask is compiled to deny; nobody is there to answer
	}
	if m := subagentModel(in); m != "" {
		cfg.Agents.DefaultSubagentModel = m
		cfg.Agents.DefaultSubagentReasoningEffort = in.Policy.Policy.Models.Effort[core.TierBalanced]
	}
	body, err := toml.Marshal(cfg)
	if err != nil {
		return nil, fmt.Errorf("codex config: %w", err)
	}
	var b bytes.Buffer
	b.WriteString("# Generated by `rr sync` from riskrails.yaml. Do not edit.\n")
	b.WriteString("# Network stays off (Codex workspace-write default); enforcement.egress.allow cannot be enforced by Codex.\n")
	b.WriteString("# .git is always read-only in the Codex sandbox, so no .git rules are emitted.\n\n")
	b.Write(body)
	return []core.File{{Path: ".codex/config.toml", Content: b.Bytes()}}, nil
}

// subagentModel resolves the BALANCED tier from the effective tiers of codex,
// following the ladder; "" when unresolved (the key is then omitted).
func subagentModel(in core.SyncInput) string {
	t, ok := in.Tiers[Name]
	if !ok {
		return ""
	}
	tier := core.TierBalanced
	for range core.Tiers { // bounded walk: a ladder cycle cannot loop forever
		if m := t.Models[tier]; m != "" {
			return m
		}
		next, ok := t.Ladder[tier]
		if !ok || next == tier {
			return ""
		}
		tier = next
	}
	return ""
}

// strictness orders access values: a path listed twice keeps the strictest.
var strictness = map[string]int{"write": 0, "read": 1, "deny": 2}

// filesystem compiles enforcement.sandbox into a Codex permission profile.
func filesystem(in core.SyncInput) map[string]any {
	enf := in.Policy.Policy.Enforcement
	refs := map[string][]string{"$secret_reads": enf.SecretReads, "$protected_paths": enf.ProtectedPaths}
	abs := map[string]string{"/": "read", "/tmp": "write"}
	ws := map[string]string{".": "write"}
	add := func(entries []string, access string) {
		for _, e := range entries {
			if r, ok := refs[e]; ok {
				for _, x := range r {
					place(abs, ws, in.Home, x, access)
				}
				continue
			}
			place(abs, ws, in.Home, e, access)
		}
	}
	add(core.AlwaysProtected, "read")
	add(enf.ProtectedPaths, "read")
	add(enf.Sandbox.Readonly, "read")
	add(enf.Sandbox.NoWrite, "read")
	add(enf.SecretReads, "deny")
	add(enf.Sandbox.NoRead, "deny")
	dropCovered(ws)
	fs := map[string]any{":workspace_roots": ws}
	for k, v := range abs {
		fs[k] = v
	}
	return fs
}

func place(abs, ws map[string]string, home, entry, access string) {
	entry = filepath.ToSlash(strings.TrimSpace(entry))
	var target map[string]string
	switch {
	case entry == "~" || strings.HasPrefix(entry, "~/"):
		entry, target = strings.TrimRight(home, "/")+entry[1:], abs
	case strings.HasPrefix(entry, "/"):
		target = abs
	}
	if target != nil && access == "read" {
		return // outside the workspace everything but /tmp is read-only already; glob "read" is invalid in Codex
	}
	switch {
	case target != nil:
	case entry == ".git" || strings.HasPrefix(entry, ".git/"):
		// .git is read-only in the Codex sandbox anyway, and a rule for an absent
		// path under it (e.g. .git/refs/remotes in a fresh repo) makes bwrap fail.
		return
	default:
		target = ws
		var ok bool
		if entry, ok = wsEntry(entry, access); !ok {
			return
		}
	}
	if cur, set := target[entry]; entry == "" || set && strictness[cur] >= strictness[access] {
		return
	}
	target[entry] = access
}

// dropCovered removes read-only entries lying under another read-only "dir/**":
// bwrap cannot create the mount point of an absent path below a read-only mount
// (observed: ".github/**" + ".github/workflows/**" fails when workflows/ is absent).
func dropCovered(ws map[string]string) {
	for k, v := range ws {
		if v != "read" {
			continue
		}
		for p, pv := range ws {
			if dir, ok := strings.CutSuffix(p, "/**"); ok && pv == "read" && p != k && strings.HasPrefix(k, dir+"/") {
				delete(ws, k)
				break
			}
		}
	}
}

const globMeta = "*?[{"

// wsEntry adapts a policy pattern to what Codex accepts under :workspace_roots
// (verified on 0.166.0): a glob path only supports "deny"; "read" needs an
// exact path or a trailing "/**". So:
//   - deny: slash-less patterns get "**/" (gitignore semantics, internal/globs);
//   - read, exact path: kept as is (root-relative; nested copies are NOT covered);
//   - read, other glob: the closest directory-level rule (literal prefix + "/**"),
//     or dropped when there is no literal directory prefix (e.g. ".env*").
//
// Residual gaps are listed in docs/research/verified/codex.md.
func wsEntry(entry, access string) (string, bool) {
	if entry == "" {
		return "", false
	}
	if access == "deny" {
		if !strings.Contains(entry, "/") {
			entry = "**/" + entry
		}
		return entry, true
	}
	if !strings.ContainsAny(entry, globMeta) {
		return entry, true
	}
	if base, ok := strings.CutSuffix(entry, "/**"); ok && !strings.ContainsAny(base, globMeta) {
		return entry, true
	}
	var prefix []string
	segs := strings.Split(entry, "/")
	for _, sg := range segs[:len(segs)-1] {
		if strings.ContainsAny(sg, globMeta) {
			break
		}
		prefix = append(prefix, sg)
	}
	if len(prefix) == 0 {
		return "", false
	}
	return strings.Join(prefix, "/") + "/**", true
}

// ---- .codex/hooks.json ----

type hooksFile struct {
	Hooks struct {
		PreToolUse []matcherGroup `json:"PreToolUse"`
	} `json:"hooks"`
}

type matcherGroup struct {
	Matcher string        `json:"matcher"`
	Hooks   []hookHandler `json:"hooks"`
}

type hookHandler struct {
	Type          string `json:"type"`
	Command       string `json:"command"`
	Timeout       int    `json:"timeout"`
	StatusMessage string `json:"statusMessage"`
}

type hooksGen struct{}

func (hooksGen) Name() string { return "codex-hooks" }

func (hooksGen) Render(context.Context, core.SyncInput) ([]core.File, error) {
	var f hooksFile
	f.Hooks.PreToolUse = []matcherGroup{{
		Matcher: hookMatcher,
		Hooks:   []hookHandler{{Type: "command", Command: hookCommand, Timeout: hookTimeout, StatusMessage: "rr guard"}},
	}}
	b, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("codex hooks: %w", err)
	}
	return []core.File{{Path: ".codex/hooks.json", Content: append(b, '\n')}}, nil
}
