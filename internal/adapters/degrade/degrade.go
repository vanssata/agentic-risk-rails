// Package degrade is the shared part of the runtimes that have no (confirmed)
// enforcing hook: Kiro, Copilot, OpenCode (DES §10 "Degrade режим"). It owns
// the single AGENTS.md section and .githooks/pre-commit generator (two
// generators on one path is a sync error, so it is not per adapter) and the
// NoHooks adapter base. Facts: docs/research/verified/degrade.md.
//
// Protection in this mode is CI (rr-verify, rr-policy-check) plus branch
// protection. The pre-commit hook and AGENTS.md are advice: `git commit
// --no-verify` skips the former, an agent may ignore the latter.
package degrade

import (
	"context"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/vanssata/agentic-risk-rails/internal/core"
	rrsync "github.com/vanssata/agentic-risk-rails/internal/sync"
	"github.com/vanssata/agentic-risk-rails/templates/precommit"
)

const (
	begin = "<!-- rr:begin generated by `rr sync`; edits inside this block are overwritten -->"
	end   = "<!-- rr:end -->"
)

func init() { rrsync.Register(Gen{}) }

// Gen renders AGENTS.md and .githooks/pre-commit.
type Gen struct{}

func (Gen) Name() string { return "degrade" }

// Render writes AGENTS.md only when it is safe: absent (created), or already
// carrying the rr markers (block replaced). A hand-written AGENTS.md without
// markers is never touched.
func (Gen) Render(_ context.Context, in core.SyncInput) ([]core.File, error) {
	files := []core.File{{Path: ".githooks/pre-commit", Content: precommit.Script, Mode: 0o755}}
	block := section(in.Policy.Policy, in.Level)
	old, err := os.ReadFile(filepath.Join(in.Root, "AGENTS.md"))
	switch {
	case os.IsNotExist(err):
		files = append(files, core.File{Path: "AGENTS.md", Content: []byte("# AGENTS.md\n\n" + block)})
	case err != nil:
		return nil, fmt.Errorf("read AGENTS.md: %w", err)
	default:
		if out, ok := replaceBlock(old, block); ok {
			files = append(files, core.File{Path: "AGENTS.md", Content: out})
		}
	}
	return files, nil
}

func replaceBlock(old []byte, block string) ([]byte, bool) {
	s := string(old)
	i := strings.Index(s, begin)
	j := strings.Index(s, end)
	if i < 0 || j < i {
		return nil, false
	}
	return []byte(s[:i] + block + strings.TrimPrefix(s[j+len(end):], "\n")), true
}

// Protected is core.AlwaysProtected plus the policy's protected paths, deduplicated.
func Protected(e core.EnforcementSpec) []string {
	seen := map[string]bool{}
	var out []string
	for _, p := range append(append([]string{}, core.AlwaysProtected...), e.ProtectedPaths...) {
		if !seen[p] {
			seen[p] = true
			out = append(out, p)
		}
	}
	return out
}

func list(title string, items []string) string {
	if len(items) == 0 {
		return ""
	}
	return "- " + title + ": `" + strings.Join(items, "`, `") + "`\n"
}

// At L≥2 there is no human to ask: ask commands are listed as forbidden (DES §8.2).
func section(p core.Policy, l core.Level) string {
	e := p.Enforcement
	deny, ask := e.Commands.Deny, e.Commands.Ask
	if l >= core.L2 {
		deny, ask = append(append([]string{}, deny...), ask...), nil
	}
	var b strings.Builder
	b.WriteString(begin + "\n## RiskRails rules (degrade mode)\n\n")
	b.WriteString("This runtime has no enforcing hook, so these rules are advice to you and are enforced only by CI and branch protection. Autonomy is capped at L1: you act under human supervision.\n\n")
	b.WriteString(list("Never write", Protected(e)))
	b.WriteString(list("Never read", e.SecretReads))
	b.WriteString(list("Forbidden commands", deny))
	b.WriteString(list("Ask the human first", ask))
	b.WriteString("\nBefore committing run `rr guard --staged`; before opening a PR run `rr verify` and `rr policy check`. ")
	b.WriteString("Enable the commit hook once per clone with `git config core.hooksPath .githooks`. `git commit --no-verify` bypasses it; CI will still reject the change.\n")
	b.WriteString(end + "\n")
	return b.String()
}

// NoHooks is the RuntimeAdapter base for runtimes without an enforcing hook:
// every hook call is an error (the caller denies) and Enforcement is ci_only.
type NoHooks struct{ ID string }

func (n NoHooks) Name() string { return n.ID }

func (n NoHooks) ParseHookInput(string, io.Reader) (core.ToolCall, error) {
	return core.ToolCall{}, fmt.Errorf("%s: no hook protocol (degrade mode)", n.ID)
}

func (n NoHooks) RenderHookOutput(_ string, _ core.ToolCall, v core.Verdict, _, stderr io.Writer) (int, error) {
	if v.Decision == core.Allow {
		return 0, nil
	}
	_, err := fmt.Fprintln(stderr, "rr: denied:", v.Reason)
	return 2, err
}

func (NoHooks) Generators() []core.Generator { return nil }

func (NoHooks) Enforcement(context.Context, string) (core.Enforcement, error) {
	return core.EnforcementCIOnly, nil
}
