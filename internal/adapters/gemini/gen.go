const (
	// hookTimeoutMS is above rr guard's own 2 s deadline; Gemini timeouts are milliseconds.
	hookTimeoutMS = 10000
	hookCommand   = "rr guard --runtime gemini --event BeforeTool || exit 2"
)

// ---- .gemini/settings.json ----

type settingsDoc struct {
	Hooks struct {
		BeforeTool []matcherGroup `json:"BeforeTool"`
	} `json:"hooks"`
}

type matcherGroup struct {
	Matcher string        `json:"matcher"`
	Hooks   []hookHandler `json:"hooks"`
}

type hookHandler struct {
	Type    string `json:"type"`
	Name    string `json:"name"`
	Command string `json:"command"`
	Timeout int    `json:"timeout"`
}

type settingsGen struct{}

func (settingsGen) Name() string { return "gemini-settings" }

func (settingsGen) Render(context.Context, core.SyncInput) ([]core.File, error) {
	var d settingsDoc
	d.Hooks.BeforeTool = []matcherGroup{{
		Matcher: ".*",
		Hooks:   []hookHandler{{Type: "command", Name: "rr-guard", Command: hookCommand, Timeout: hookTimeoutMS}},
	}}
	b, err := json.MarshalIndent(d, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("gemini settings: %w", err)
	}
	return []core.File{{Path: ".gemini/settings.json", Content: append(b, '\n')}}, nil
}

// ---- .gemini/policies/riskrails.toml ----

type policyDoc struct {
	Rule []rule `toml:"rule"`
}

type rule struct {
	ToolName    []string `toml:"toolName"`
	CommandRe   string   `toml:"commandRegex,omitempty"`
	ArgsPattern string   `toml:"argsPattern,omitempty"`
	Decision    string   `toml:"decision"`
	Priority    int      `toml:"priority"`
	DenyMessage string   `toml:"denyMessage,omitempty"`
}

type policyGen struct{}

func (policyGen) Name() string { return "gemini-policy" }

const (
	prioDeny  = 900
	prioAsk   = 500
	prioAllow = 100
)

func (policyGen) Render(_ context.Context, in core.SyncInput) ([]core.File, error) {
	e := in.Policy.Policy.Enforcement
	sb := e.Sandbox
	var doc policyDoc
	add := func(r rule) { doc.Rule = append(doc.Rule, r) }

	if re := commandRegex(e.Commands.Deny); re != "" {
		add(rule{ToolName: []string{"run_shell_command"}, CommandRe: re, Decision: "deny", Priority: prioDeny, DenyMessage: "denied by riskrails.yaml enforcement.commands.deny"})
	}
	if re := pathArgs(concat(core.AlwaysProtected, e.ProtectedPaths, sb.Readonly, sb.NoWrite), e.SecretReads); re != "" {
		add(rule{ToolName: []string{"write_file", "replace"}, ArgsPattern: re, Decision: "deny", Priority: prioDeny, DenyMessage: "protected path (riskrails.yaml)"})
	}
	if re := pathArgs(concat(e.SecretReads, sb.NoRead), e.SecretReads); re != "" {
		add(rule{ToolName: []string{"read_file"}, ArgsPattern: re, Decision: "deny", Priority: prioDeny, DenyMessage: "secret path (riskrails.yaml)"})
	}
	if re := commandRegex(e.Commands.Ask); re != "" {
		r := rule{ToolName: []string{"run_shell_command"}, CommandRe: re, Decision: "ask_user", Priority: prioAsk}
		if in.Level >= core.L2 {
			r.Decision, r.DenyMessage = "deny", "needs approval; no human present at L2+"
		}
		add(r)
	}
	if re := commandRegex(e.Commands.Allow); re != "" {
		add(rule{ToolName: []string{"run_shell_command"}, CommandRe: re, Decision: "allow", Priority: prioAllow})
	}
	body, err := toml.Marshal(doc)
	if err != nil {
		return nil, fmt.Errorf("gemini policy: %w", err)
	}
	var b bytes.Buffer
	b.WriteString("# Generated by `rr sync` from riskrails.yaml. Do not edit.\n")
	b.WriteString("# The Gemini CLI workspace policy tier is currently disabled upstream (issue #18186):\n")
	b.WriteString("# this file only takes effect when copied to ~/.gemini/policies/ or an admin policy dir.\n")
	b.WriteString("# Enforcement in the project comes from the BeforeTool hook in .gemini/settings.json.\n\n")
	b.Write(body)
	return []core.File{{Path: ".gemini/policies/riskrails.toml", Content: b.Bytes()}}, nil
}

// commandRegex turns glob command patterns ("git push*") into one anchored regex.
func commandRegex(globs []string) string {
	if len(globs) == 0 {
		return ""
	}
	alts := make([]string, len(globs))
	for i, g := range globs {
		alts[i] = strings.ReplaceAll(regexp.QuoteMeta(g), `\*`, ".*")
	}
	return "^(?:" + strings.Join(alts, "|") + ")$"
}

// pathArgs builds an argsPattern matching file_path against path globs.
// Relative globs match as a path suffix at any depth (stricter than the
// root-anchored policy meaning, which is the safe side); "~/" is expanded with
// home; "$secret_reads" is replaced with secrets, other "$" refs are dropped.
func pathArgs(globs, secrets []string) string {
	var alts []string
	seen := map[string]bool{}
	for _, g := range globs {
		switch {
		case g == "$secret_reads":
			alts = appendUniq(alts, seen, secrets...)
		case strings.HasPrefix(g, "$"):
		default:
			alts = appendUniq(alts, seen, g)
		}
	}
	if len(alts) == 0 {
		return ""
	}
	return `"file_path":"(?:` + strings.Join(alts, "|") + `)"`
}

func appendUniq(alts []string, seen map[string]bool, globs ...string) []string {
	for _, g := range globs {
		prefix := `(?:.*/)?`
		if rest, ok := strings.CutPrefix(g, "~/"); ok {
			g = rest // any home, `~` or absolute: over-matching a deny is safe, and manifests must not depend on the machine
		} else if strings.HasPrefix(g, "/") {
			prefix = ""
		}
		re := prefix + globRegex(strings.TrimPrefix(g, "./"))
		if !seen[re] {
			seen[re] = true
			alts = append(alts, re)
		}
	}
	return alts
}

func globRegex(g string) string {
	var b strings.Builder
	for i := 0; i < len(g); i++ {
		switch c := g[i]; {
		case c == '*' && i+1 < len(g) && g[i+1] == '*':
			b.WriteString(".*")
			i++
		case c == '*':
			b.WriteString("[^/]*")
		case c == '?':
			b.WriteString("[^/]")
		default:
			b.WriteString(regexp.QuoteMeta(string(c)))
		}
	}
	return b.String()
}

func concat(lists ...[]string) []string {
	var out []string
	for _, l := range lists {
		out = append(out, l...)
	}
	return out
}

