type agentsGen struct{}

func (agentsGen) Name() string { return "gemini-agents" }

func (agentsGen) Render(_ context.Context, in core.SyncInput) ([]core.File, error) {
	t := in.Tiers[Name]
	var files []core.File
	for _, a := range agentSpecs {
		var b strings.Builder
		fmt.Fprintf(&b, "---\nname: %s\ndescription: %s\nkind: local\n", a.file, a.desc)
		if a.tools != "" {
			b.WriteString("tools:\n" + a.tools)
		}
		// A tier without a PASS model omits the line: the agent inherits the session model.
		if m := resolveModel(t, a.tier); m != "" {
			fmt.Fprintf(&b, "model: %s\n", m)
		}
		b.WriteString("max_turns: 30\ntimeout_mins: 10\n---\n\n" + a.body + "\n")
		files = append(files, core.File{Path: ".gemini/agents/" + a.file + ".md", Content: []byte(b.String())})
	}
	return files, nil
}

// resolveModel returns the PASS model for tier, following the ladder; "" if none.
func resolveModel(t core.EffectiveTiers, tier core.Tier) string {
	for i := 0; i <= len(core.Tiers) && tier != ""; i++ {
		if m := t.Models[tier]; m != "" {
			return m
		}
		tier = t.Ladder[tier]
	}
	return ""
}
