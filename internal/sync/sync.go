// Package sync renders manifests from registered generators (rr sync) and
// detects drift between generated and on-disk files (rr sync --check).
package sync

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"
	gosync "sync"

	"github.com/vanssata/agentic-risk-rails/internal/core"
)

var (
	mu   gosync.Mutex
	gens []core.Generator
	// runtimeOf maps a generator name to the runtime it belongs to; generators
	// registered with Register are runtime-neutral and are not listed.
	runtimeOf = map[string]string{}
	known     = map[string]bool{}
)

// RegisterRuntime declares a runtime name (valid in project.runtimes) and
// registers its generators, which rr sync renders only while the runtime is enabled.
func RegisterRuntime(name string, gs ...core.Generator) {
	mu.Lock()
	known[name] = true
	for _, g := range gs {
		runtimeOf[g.Name()] = name
	}
	mu.Unlock()
	for _, g := range gs {
		Register(g)
	}
}

// Register adds a generator; adapters call it from init().
func Register(g core.Generator) {
	mu.Lock()
	defer mu.Unlock()
	gens = append(gens, g)
}

// Generators returns registered generators sorted by name.
func Generators() []core.Generator {
	mu.Lock()
	defer mu.Unlock()
	out := append([]core.Generator(nil), gens...)
	sort.Slice(out, func(i, j int) bool { return out[i].Name() < out[j].Name() })
	return out
}

// enabled reports whether g renders under project.runtimes (nil = all). A name
// that is not a registered runtime is an error (fail-closed).
func enabled(g core.Generator, rts []string) bool {
	mu.Lock()
	defer mu.Unlock()
	rt, ok := runtimeOf[g.Name()]
	return rts == nil || !ok || slices.Contains(rts, rt)
}

// checkRuntimes rejects names that are not registered runtimes (fail-closed).
func checkRuntimes(rts []string) error {
	mu.Lock()
	defer mu.Unlock()
	for _, rt := range rts {
		if !known[rt] {
			return fmt.Errorf("project.runtimes: unknown runtime %q", rt)
		}
	}
	return nil
}

// Render collects files from gens, skipping generators of runtimes not listed
// in project.runtimes. Two generators writing the same path is an error.
func Render(ctx context.Context, in core.SyncInput, gens []core.Generator) ([]core.File, error) {
	owner := map[string]string{}
	var files []core.File
	if err := checkRuntimes(in.Policy.Policy.Project.Runtimes); err != nil {
		return nil, err
	}
	for _, g := range gens {
		if !enabled(g, in.Policy.Policy.Project.Runtimes) {
			continue
		}
		fs, err := g.Render(ctx, in)
		if err != nil {
			return nil, fmt.Errorf("generator %s: %w", g.Name(), err)
		}
		for _, f := range fs {
			p := filepath.Clean(f.Path)
			if filepath.IsAbs(p) || p == ".." || len(p) > 2 && p[:3] == "../" {
				return nil, fmt.Errorf("generator %s: path %q escapes the repo", g.Name(), f.Path)
			}
			if o, dup := owner[p]; dup {
				return nil, fmt.Errorf("path %s generated by both %s and %s", p, o, g.Name())
			}
			owner[p] = g.Name()
			f.Path = p
			files = append(files, f)
		}
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	return files, nil
}

// Stale returns the paths, existing under root, that generators of runtimes
// disabled in project.runtimes would render for the current input. They are
// rendered only to learn their paths; paths also produced by an enabled
// generator are never stale.
func Stale(ctx context.Context, root string, in core.SyncInput, gens []core.Generator) ([]string, error) {
	rts := in.Policy.Policy.Project.Runtimes
	if err := checkRuntimes(rts); err != nil {
		return nil, err
	}
	keep := map[string]bool{}
	var off []core.Generator
	for _, g := range gens {
		if enabled(g, rts) {
			fs, err := g.Render(ctx, in)
			if err != nil {
				return nil, fmt.Errorf("generator %s: %w", g.Name(), err)
			}
			for _, f := range fs {
				keep[filepath.Clean(f.Path)] = true
			}
		} else {
			off = append(off, g)
		}
	}
	seen := map[string]bool{}
	var out []string
	for _, g := range off {
		fs, err := g.Render(ctx, in)
		if err != nil {
			return nil, fmt.Errorf("generator %s: %w", g.Name(), err)
		}
		for _, f := range fs {
			p := filepath.Clean(f.Path)
			if filepath.IsAbs(p) || p == ".." || strings.HasPrefix(p, "../") {
				return nil, fmt.Errorf("generator %s: path %q escapes the repo", g.Name(), f.Path)
			}
			if keep[p] || seen[p] {
				continue
			}
			seen[p] = true
			if _, err := os.Lstat(filepath.Join(root, p)); err == nil {
				out = append(out, p)
			} else if !os.IsNotExist(err) {
				return nil, err
			}
		}
	}
	sort.Strings(out)
	return out, nil
}

// Remove deletes exactly the given files under root (never directories; a
// symlink is removed, not followed). A path whose parent directory resolves
// outside root is refused.
func Remove(root string, paths []string) error {
	realRoot, err := filepath.EvalSymlinks(root)
	if err != nil {
		return err
	}
	for _, p := range paths {
		dst := filepath.Join(root, p)
		dir, err := filepath.EvalSymlinks(filepath.Dir(dst))
		if err != nil {
			return err
		}
		if dir != realRoot && !strings.HasPrefix(dir, realRoot+string(filepath.Separator)) {
			return fmt.Errorf("refusing to remove %s: parent resolves outside the repo", p)
		}
		if fi, err := os.Lstat(dst); err != nil {
			return err
		} else if fi.IsDir() {
			return fmt.Errorf("refusing to remove directory %s", p)
		}
		if err := os.Remove(dst); err != nil {
			return err
		}
	}
	return nil
}

// Write writes files under root.
func Write(root string, files []core.File) error {
	for _, f := range files {
		dst := filepath.Join(root, f.Path)
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return err
		}
		mode := os.FileMode(f.Mode)
		if mode == 0 {
			mode = 0o644
		}
		if err := os.WriteFile(dst, f.Content, mode); err != nil {
			return err
		}
	}
	return nil
}

// Drift returns the paths whose on-disk content differs from files (missing counts).
func Drift(root string, files []core.File) ([]string, error) {
	var out []string
	for _, f := range files {
		b, err := os.ReadFile(filepath.Join(root, f.Path))
		if err != nil && !os.IsNotExist(err) {
			return nil, err
		}
		if err != nil || !bytes.Equal(b, f.Content) {
			out = append(out, f.Path)
		}
	}
	return out, nil
}

// InputProvider builds the SyncInput for a repo root. The orchestrator wires
// the real one (policy resolver + model resolver) between waves; until then
// generators get the fully defaulted strict policy at L1.
var InputProvider = func(_ context.Context, root string) (core.SyncInput, error) {
	home, _ := os.UserHomeDir()
	strict := core.StrictDefaults()
	return core.SyncInput{
		Root: root, Home: home, Level: core.L1,
		Policy: core.EffectivePolicy{Policy: strict, InForce: strict},
	}, nil
}
